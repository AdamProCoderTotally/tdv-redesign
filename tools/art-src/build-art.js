"use strict";
// node tools/art-src/build-art.js  ->  js/artpack.js
// Regenerates every ART V2 sprite in the game's own sprite format
// ({w,h,pal,rows} + frames, ax/ay anchor, tip muzzle). Rows are stored
// run-length encoded (see rle() below) and expanded by js/art.js at load,
// so the runtime still hands drawSpriteRows() plain rows.
// To migrate to PNG sheets later: iterate ART the same way and blit each
// frame into an atlas instead of serialising rows; nothing else changes.
const fs=require('fs'),path=require('path');
const {R}=require('./pix');
const {buildTower}=require('./towers');const {buildFarm,buildVillage}=require('./buildings');
const en=require('./enemies');const fx=require('./fx');const deco=require('./deco');const ash=require('./ash');
const ART={towers:{},enemies:{},fx:{},deco:{}};
// ---- towers: key type_tier_lane (tier 0 has lane 0 only) ----
const TW={ranger:2,grenadier:2,sniper:2,phaser:1,viper:2,voidtraitor:1};
for(const [type,lanes] of Object.entries(TW))for(let tier=0;tier<=5;tier++)for(let lane=0;lane<lanes;lane++){
  if(tier===0&&lane>0)continue;ART.towers[type+'_'+tier+'_'+lane]=buildTower(type,tier,lane)}
// prestige towers: gold re-ramp + hand-placed trim (helmet rim, weapon top line)
for(const [gold,type] of [['goldranger','ranger'],['goldgrenadier','grenadier']])for(let tier=0;tier<=5;tier++)for(let lane=0;lane<2;lane++){
  if(tier===0&&lane>0)continue;ART.towers[gold+'_'+tier+'_'+lane]=buildTower(type,tier,lane,{gold:1})}
for(let tier=0;tier<=5;tier++){ART.towers['farm_'+tier+'_0']=buildFarm(tier);for(let lane=0;lane<2;lane++){if(tier===0&&lane>0)continue;ART.towers['village_'+tier+'_'+lane]=buildVillage(tier,lane)}}
// ---- enemies + bosses: key = config kind; 8 frames (front walk 0-3, back walk 4-7) ----
for(const k of en.KINDS)ART.enemies[k]=en.build(k);
// ---- effects ----
const M=fx.muzzle(),DP=fx.deathpuff(),BD=fx.bossdeath();
ART.fx={muzzle:M,muzzle_blue:fx.recolor(M,R.fire,R.blue),muzzle_toxic:fx.recolor(M,R.fire,R.toxic),muzzle_void:fx.recolor(M,R.fire,R.void),
  spark:fx.spark(),explosion:fx.explosion(),grenade:fx.grenade(),
  deathpuff:DP,death_blood:fx.recolor(DP,fx.ECTO,R.flesh),death_void:fx.recolor(DP,fx.ECTO,R.void),death_ember:fx.recolor(DP,fx.ECTO,R.fire),death_dust:fx.recolor(DP,fx.ECTO,R.stone),
  bossdeath:BD,bossdeath_void:fx.recolor(BD,R.fire,R.void,{'rgba(255,200,140,.5)':'rgba(192,138,255,.5)'}),
  tracer_bullet:fx.tracer('bullet'),tracer_laser:fx.tracer('laser'),tracer_plasma:fx.tracer('plasma')};
ART.deco=Object.assign(deco.build(),ash.build());
// ---- serialise (RLE rows) ----
// token = one base-36 palette char or '.', optionally followed by *<count>; (for runs of 3+)
function rle(row){let o='';for(let i=0;i<row.length;){let j=i;while(j<row.length&&row[j]===row[i])j++;const n=j-i;o+=n>=3?row[i]+'*'+n+';':row[i].repeat(n);i=j}return o}
function pack(s){const o=Object.assign({},s);if(o.frames){o.frames=o.frames.map(f=>f.map(rle));delete o.rows}else o.rows=o.rows.map(rle);o.rle=1;return o}
const out=path.join(__dirname,'../../js/artpack.js');
let src='"use strict";\n// ============================================================\n//  artpack.js — GENERATED by tools/art-src/build-art.js. Do not hand-edit;\n//  change the generator and re-run it. Every entry is a sprite in the\n//  game\'s own format {w,h,pal,rows} (+ frames, ax/ay anchor, tip muzzle),\n//  rows run-length encoded (rle:1) and expanded by js/art.js on load.\n// ============================================================\nvar ART={\n';
for(const grp of Object.keys(ART)){src+=' '+grp+':{\n';for(const [k,v] of Object.entries(ART[grp]))src+='  '+JSON.stringify(k)+':'+JSON.stringify(pack(v))+',\n';src+=' },\n'}
src+='};\n';fs.writeFileSync(out,src);
console.log('wrote',out,(src.length/1024).toFixed(0)+'KB',Object.keys(ART.towers).length,'towers',Object.keys(ART.enemies).length,'enemies',Object.keys(ART.fx).length,'fx',Object.keys(ART.deco).length,'deco');
